// src/bin/fsbackup.rs
//
// Low-level backup executor CLI — demonstrates LocalFileBackup and NfsFileBackup
// from the frame::traits layer directly.
//
// This tool exercises the backup subtask phase in isolation (no scan, no
// manifest, no post-job).  For the full integrated workflow, use `fptcli backup`.

use std::path::PathBuf;
use clap::Parser;
use log::info;

use bifrost::backup::aggregate::AggregateConfig;
use bifrost::frame::{
    BackupConfig,
    FileBackup,
    LocalFileBackup,
};
#[cfg(feature = "nfs")]
use bifrost::frame::NfsFileBackup;
#[cfg(feature = "nfs")]
use bifrost::nfs::NfsLocation;

/// Bifrost Backup Executor
///
/// Executes a single backup subtask from a control file generated by `fsscan`.
/// Supports both local and NFS targets via the FileBackup trait.
#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None)]
struct Args {
    /// Source base directory (used to construct source file paths)
    #[arg(long, short = 's', required = true, value_name = "DIR")]
    source_dir: PathBuf,

    /// Target base directory for backup output (local FS).
    /// Ignored when --nfs-target-host is set.
    #[arg(long, short = 't', required = true, value_name = "DIR")]
    target_dir: PathBuf,

    /// Metadata directory containing meta_*.dat files
    #[arg(long, short = 'm', required = true, value_name = "DIR")]
    meta_dir: PathBuf,

    /// Control file path (generated by fsscan)
    #[arg(long, short = 'c', required = true, value_name = "FILE")]
    control_file: PathBuf,

    /// Control directory containing hardlink.txt etc. (defaults to control file's parent dir)
    #[arg(long, value_name = "DIR")]
    ctrl_dir: Option<PathBuf>,

    /// Enable hardlink phase after copy phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    hardlink: bool,

    /// Enable delete phase after hardlink phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    delete: bool,

    /// Enable mtime phase after copy/hardlink phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    mtime: bool,

    /// Enable aggregate backup mode (combines small files into blobs)
    #[arg(long, action = clap::ArgAction::SetTrue)]
    aggregate: bool,

    /// Maximum size of aggregate blob files in MB [default: 64]
    #[arg(long, value_name = "SIZE_MB", default_value = "64")]
    max_blob_size: u64,

    /// File size threshold for aggregation in KB [default: 1024]
    #[arg(long, value_name = "SIZE_KB", default_value = "1024")]
    aggregate_threshold: u64,

    // ── NFS target options (require --features nfs) ──────────────────────────
    /// NFS target: server IP or hostname.
    /// When set, files are written to the NFS server via the AIO pipeline
    /// instead of the local --target-dir.
    #[arg(long, value_name = "HOST", requires = "nfs_target_export")]
    nfs_target_host: Option<String>,

    /// NFS target: export path on the server (e.g. /export/backup).
    #[arg(long, value_name = "PATH", requires = "nfs_target_host")]
    nfs_target_export: Option<String>,

    /// NFS target: sub-path within the export to use as the working root.
    #[arg(long, value_name = "PATH")]
    nfs_target_sub_path: Option<String>,

    /// NFS target: number of parallel TCP connections [default: 4]
    #[arg(long, value_name = "N", default_value = "4")]
    nfs_target_connections: usize,

    /// Verbose logging (-v=INFO, -vv=DEBUG, -vvv=TRACE)
    #[arg(short, long, action = clap::ArgAction::Count)]
    verbose: u8,

    /// Log file path (append mode; logs also go to stdout)
    #[arg(long, value_name = "FILE")]
    log_file: Option<PathBuf>,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();

    // Initialise logger: stdout + optional file.
    bifrost::logging::init(args.verbose);
    if let Some(ref p) = args.log_file {
        bifrost::logging::add_file(p);
    }

    // Validate inputs.
    if !args.meta_dir.exists() {
        return Err(format!("Metadata directory does not exist: {}", args.meta_dir.display()).into());
    }
    if !args.control_file.exists() {
        return Err(format!("Control file does not exist: {}", args.control_file.display()).into());
    }

    let ctrl_dir = args.ctrl_dir.unwrap_or_else(|| {
        args.control_file.parent()
            .unwrap_or(args.meta_dir.as_path())
            .to_path_buf()
    });

    // Build the shared BackupConfig.
    let aggregate_config = if args.aggregate {
        info!("Aggregate backup enabled: max_blob_size={}MB, threshold={}KB",
              args.max_blob_size, args.aggregate_threshold);
        AggregateConfig::enabled()
            .max_blob_size(args.max_blob_size * 1024 * 1024)
            .file_threshold(args.aggregate_threshold * 1024)
    } else {
        AggregateConfig::default()
    };

    let backup_cfg = BackupConfig::new(
        args.source_dir.clone(),
        args.target_dir.clone(),
        args.meta_dir.clone(),
        ctrl_dir,
        args.control_file.clone(),
    )
    .aggregate_config(aggregate_config)
    .enable_hardlink(args.hardlink)
    .enable_delete(args.delete)
    .enable_mtime(args.mtime);

    // ── NFS target branch ─────────────────────────────────────────────────────
    #[cfg(feature = "nfs")]
    if let Some(ref host) = args.nfs_target_host {
        let export = args.nfs_target_export.as_deref().unwrap_or("");
        let mut loc = NfsLocation::new(host, export)
            .connection_count(args.nfs_target_connections);
        if let Some(ref sub) = args.nfs_target_sub_path {
            loc = loc.sub_path(sub);
        }
        info!("NFS target: {}:{} sub_path={:?} connections={}",
              host, export,
              args.nfs_target_sub_path.as_deref().unwrap_or(""),
              args.nfs_target_connections);

        info!("Starting NFS backup task");
        let stats = NfsFileBackup::new(backup_cfg, loc).run()?;
        print_summary(&stats);
        return Ok(());
    }

    #[cfg(not(feature = "nfs"))]
    if args.nfs_target_host.is_some() {
        return Err("NFS target requested but binary was built without the `nfs` feature.\n\
                    Rebuild with: cargo build --features nfs".into());
    }

    // ── Local target branch ───────────────────────────────────────────────────
    info!("Starting local backup task");
    let stats = LocalFileBackup::new(backup_cfg).run()?;
    print_summary(&stats);

    Ok(())
}

fn print_summary(stats: &bifrost::frame::TransferStats) {
    println!(
        "Backup complete: {} files ({:.2} MB), {} dirs, {} failed",
        stats.files_transferred,
        stats.bytes_transferred as f64 / (1024.0 * 1024.0),
        stats.dirs_created,
        stats.files_failed,
    );
}
