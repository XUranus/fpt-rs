// src/bin/fsbackup.rs
//
// Low-level backup executor CLI — demonstrates LocalFileBackup and NfsFileBackup
// from the frame::traits layer directly.
//
// This tool exercises the backup subtask phase in isolation (no scan, no
// manifest, no post-job).  For the full integrated workflow, use `fptcli backup`.

use clap::{Parser, ValueEnum};
use log::info;
use std::path::PathBuf;
use std::time::{Duration, Instant};

use bifrost::backup::aggregate::{AggregateConfig, AggregateLayout};
use bifrost::failure::{failure_file_path, FailureLogConfig, FailureLogFormat, RetryPolicy};
#[cfg(feature = "nfs")]
use bifrost::frame::backup_impls::{NfsSourceFileBackup, NfsSourceTargetFileBackup};
#[cfg(all(feature = "nfs", feature = "smb"))]
use bifrost::frame::backup_impls::{NfsSourceSmbTargetFileBackup, SmbSourceNfsTargetFileBackup};
#[cfg(feature = "smb")]
use bifrost::frame::backup_impls::{SmbFileBackup, SmbSourceFileBackup, SmbSourceTargetFileBackup};
#[cfg(feature = "nfs")]
use bifrost::frame::NfsFileBackup;
use bifrost::frame::{BackupConfig, DataLocation, FileBackup, LocalFileBackup};

/// Bifrost Backup Executor
///
/// Executes a single backup subtask from a control file generated by `fsscan`.
/// Supports both local and NFS targets via the FileBackup trait.
#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None)]
struct Args {
    /// Source base directory (used to construct source file paths)
    #[arg(long, short = 's', required = true, value_name = "DIR")]
    source_dir: String,

    /// Target base directory for backup output (local FS).
    /// Ignored when --nfs-target-host is set.
    #[arg(long, short = 't', required = true, value_name = "DIR")]
    target_dir: String,

    /// Metadata directory containing meta_*.dat files
    #[arg(long, short = 'm', required = true, value_name = "DIR")]
    meta_dir: PathBuf,

    /// Control file path (generated by fsscan)
    #[arg(long, short = 'c', required = true, value_name = "FILE")]
    control_file: PathBuf,

    /// Control directory containing hardlink.txt etc. (defaults to control file's parent dir)
    #[arg(long, value_name = "DIR")]
    ctrl_dir: Option<PathBuf>,

    /// Enable hardlink phase after copy phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    hardlink: bool,

    /// Enable delete phase after hardlink phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    delete: bool,

    /// Enable mtime phase after copy/hardlink phase
    #[arg(long, action = clap::ArgAction::SetTrue)]
    mtime: bool,

    /// Enable aggregate backup mode (combines small files into blobs)
    #[arg(long, action = clap::ArgAction::SetTrue)]
    aggregate: bool,

    /// Maximum size of aggregate blob files in MB [default: 4]
    #[arg(long, value_name = "SIZE_MB", default_value = "4")]
    max_blob_size: u64,

    /// File size threshold for aggregation in KB [default: 1024]
    #[arg(long, value_name = "SIZE_KB", default_value = "1024")]
    aggregate_threshold: u64,

    /// Aggregate layout/version: `dir-level` or `shard`
    #[arg(long, value_enum, default_value = "shard")]
    aggregate_layout: AggregateLayoutArg,
    /// Number of parallel NFS connections [default: 32]
    #[arg(long, value_name = "N", default_value = "32")]
    nfs_connections: usize,

    /// Number of SMB client connections per SMB endpoint [default: 1]
    #[arg(long, value_name = "N", default_value = "4")]
    smb_connections: usize,

    /// Maximum per-file copy buffer size in KB [default: 1024, recommended: 256..4096].
    /// SMB source reads are capped at 2048 KiB; SMB writes stay capped at 256 KiB.
    #[arg(long, value_name = "SIZE_KB", default_value = "1024")]
    buffer_size: usize,

    /// Structured failure log output path. If omitted and --failure-log-format is set,
    /// defaults to <ctrl-dir>/FSBACKUP_FAILURE.<ext>.
    #[arg(long, value_name = "FILE")]
    failure_log: Option<PathBuf>,

    /// Structured failure log format.
    #[arg(long, value_enum, value_name = "FMT")]
    failure_log_format: Option<FailureLogFormatArg>,

    /// Number of retries for copy operations before recording failure.
    #[arg(long, default_value = "3", value_name = "COUNT")]
    operation_retries: u32,

    /// Delay in milliseconds between retries.
    #[arg(long, default_value = "1000", value_name = "MS")]
    retry_delay_ms: u64,

    /// Exponential retry backoff multiplier. 1.0 keeps fixed delay.
    #[arg(long, default_value = "1.0", value_name = "N")]
    retry_backoff: f64,

    /// Maximum retry delay in milliseconds when backoff is enabled.
    #[arg(long, default_value = "1000", value_name = "MS")]
    retry_max_delay_ms: u64,

    /// Deterministic jitter ratio for retry delays, range 0.0..1.0.
    #[arg(long, default_value = "0.0", value_name = "RATIO")]
    retry_jitter: f64,

    /// AUTH_UNIX uid to present to the NFS server (overrides uid= in URL)
    #[arg(long, value_name = "UID")]
    nfs_uid: Option<u32>,

    /// AUTH_UNIX gid to present to the NFS server (overrides gid= in URL)
    #[arg(long, value_name = "GID")]
    nfs_gid: Option<u32>,

    /// Verbose logging (-v=INFO, -vv=DEBUG, -vvv=TRACE)
    #[arg(short, long, action = clap::ArgAction::Count)]
    verbose: u8,

    /// Log file path (append mode; logs also go to stdout)
    #[arg(long, value_name = "FILE")]
    log_file: Option<PathBuf>,
}

#[derive(ValueEnum, Debug, Clone, Copy)]
enum AggregateLayoutArg {
    DirLevel,
    Shard,
}

#[derive(ValueEnum, Debug, Clone, Copy)]
enum FailureLogFormatArg {
    Csv,
    Json,
    Xml,
}

impl From<AggregateLayoutArg> for AggregateLayout {
    fn from(value: AggregateLayoutArg) -> Self {
        match value {
            AggregateLayoutArg::DirLevel => AggregateLayout::DirLevel,
            AggregateLayoutArg::Shard => AggregateLayout::Shard,
        }
    }
}

impl From<FailureLogFormatArg> for FailureLogFormat {
    fn from(value: FailureLogFormatArg) -> Self {
        match value {
            FailureLogFormatArg::Csv => FailureLogFormat::Csv,
            FailureLogFormatArg::Json => FailureLogFormat::Json,
            FailureLogFormatArg::Xml => FailureLogFormat::Xml,
        }
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();

    // Initialise logger: stdout + optional file.
    bifrost::logging::init(args.verbose);
    if let Some(ref p) = args.log_file {
        bifrost::logging::add_file(p);
    }

    // Validate inputs.
    if !args.meta_dir.exists() {
        return Err(format!(
            "Metadata directory does not exist: {}",
            args.meta_dir.display()
        )
        .into());
    }
    if !args.control_file.exists() {
        return Err(format!(
            "Control file does not exist: {}",
            args.control_file.display()
        )
        .into());
    }

    let ctrl_dir = args.ctrl_dir.unwrap_or_else(|| {
        args.control_file
            .parent()
            .unwrap_or(args.meta_dir.as_path())
            .to_path_buf()
    });
    let retry_policy = RetryPolicy::new(
        args.operation_retries,
        Duration::from_millis(args.retry_delay_ms),
    )
    .with_backoff(
        args.retry_backoff,
        Duration::from_millis(args.retry_max_delay_ms),
    )
    .with_jitter(args.retry_jitter);
    let failure_log = args.failure_log_format.map(|format| {
        let format: FailureLogFormat = format.into();
        let path = args
            .failure_log
            .clone()
            .unwrap_or_else(|| failure_file_path(&ctrl_dir, "FSBACKUP_FAILURE", format));
        FailureLogConfig::new(path, format)
    });

    // Build the shared BackupConfig.
    let aggregate_config = if args.aggregate {
        info!(
            "Aggregate backup enabled: layout={}, max_blob_size={}MB, threshold={}KB",
            AggregateLayout::from(args.aggregate_layout).as_str(),
            args.max_blob_size,
            args.aggregate_threshold
        );
        AggregateConfig::enabled()
            .layout(args.aggregate_layout.into())
            .max_blob_size(args.max_blob_size * 1024 * 1024)
            .file_threshold(args.aggregate_threshold * 1024)
    } else {
        AggregateConfig::default()
    };

    let source = parse_data_location(
        &args.source_dir,
        args.nfs_connections,
        args.nfs_uid,
        args.nfs_gid,
    )?;
    let target = parse_data_location(
        &args.target_dir,
        args.nfs_connections,
        args.nfs_uid,
        args.nfs_gid,
    )?;
    let local_target_dir = match &target {
        DataLocation::Local(path) => path.clone(),
        _ => PathBuf::from("/"),
    };

    let backup_cfg = BackupConfig::new(
        source.base_path(),
        local_target_dir,
        args.meta_dir.clone(),
        ctrl_dir,
        args.control_file.clone(),
    )
    .aggregate_config(aggregate_config)
    .remote_target_prefix((!target.is_local()).then(|| String::new()))
    .smb_connection_count(args.smb_connections)
    .copy_buffer_size(args.buffer_size * 1024)
    .failure_log(failure_log)
    .retry_policy(retry_policy)
    .enable_hardlink(args.hardlink)
    .enable_delete(args.delete)
    .enable_mtime(args.mtime);

    info!("Starting backup task: source={} target={}", source, target);
    let started = Instant::now();
    let stats = run_backup(backup_cfg, &source, &target)?;
    print_summary(&stats, started.elapsed());

    Ok(())
}

fn run_backup(
    backup_cfg: BackupConfig,
    source: &DataLocation,
    target: &DataLocation,
) -> Result<bifrost::frame::TransferStats, Box<dyn std::error::Error>> {
    match (source, target) {
        (DataLocation::Local(_), DataLocation::Local(_)) => {
            Ok(LocalFileBackup::new(backup_cfg).run()?)
        }
        #[cfg(feature = "nfs")]
        (DataLocation::Local(_), DataLocation::Nfs(nfs_target)) => {
            Ok(NfsFileBackup::new(backup_cfg, nfs_target.clone()).run()?)
        }
        #[cfg(feature = "nfs")]
        (DataLocation::Nfs(nfs_source), DataLocation::Local(_)) => {
            Ok(NfsSourceFileBackup::new(backup_cfg, nfs_source.clone()).run()?)
        }
        #[cfg(feature = "nfs")]
        (DataLocation::Nfs(nfs_source), DataLocation::Nfs(nfs_target)) => Ok(
            NfsSourceTargetFileBackup::new(backup_cfg, nfs_source.clone(), nfs_target.clone())
                .run()?,
        ),
        #[cfg(feature = "smb")]
        (DataLocation::Local(_), DataLocation::Smb(smb_target)) => {
            Ok(SmbFileBackup::new(backup_cfg, smb_target.clone()).run()?)
        }
        #[cfg(feature = "smb")]
        (DataLocation::Smb(smb_source), DataLocation::Local(_)) => {
            Ok(SmbSourceFileBackup::new(backup_cfg, smb_source.clone()).run()?)
        }
        #[cfg(feature = "smb")]
        (DataLocation::Smb(smb_source), DataLocation::Smb(smb_target)) => Ok(
            SmbSourceTargetFileBackup::new(backup_cfg, smb_source.clone(), smb_target.clone())
                .run()?,
        ),
        #[cfg(all(feature = "nfs", feature = "smb"))]
        (DataLocation::Nfs(nfs_source), DataLocation::Smb(smb_target)) => Ok(
            NfsSourceSmbTargetFileBackup::new(backup_cfg, nfs_source.clone(), smb_target.clone())
                .run()?,
        ),
        #[cfg(all(feature = "nfs", feature = "smb"))]
        (DataLocation::Smb(smb_source), DataLocation::Nfs(nfs_target)) => Ok(
            SmbSourceNfsTargetFileBackup::new(backup_cfg, smb_source.clone(), nfs_target.clone())
                .run()?,
        ),
        #[allow(unreachable_patterns)]
        _ => Err("Unsupported source/target combination for this build".into()),
    }
}

#[cfg(feature = "nfs")]
fn parse_nfs_location(
    url: &str,
    connections: usize,
    uid: Option<u32>,
    gid: Option<u32>,
) -> Result<DataLocation, Box<dyn std::error::Error>> {
    let mut loc = bifrost::nfs::NfsLocation::from_url(url)?.connection_count(connections);
    let default_uid = if loc.uid == 0 {
        unsafe { libc::geteuid() as u32 }
    } else {
        loc.uid
    };
    let default_gid = if loc.gid == 0 {
        unsafe { libc::getegid() as u32 }
    } else {
        loc.gid
    };
    loc = loc.credentials(uid.unwrap_or(default_uid), gid.unwrap_or(default_gid));
    Ok(DataLocation::nfs(loc))
}

fn parse_data_location(
    spec: &str,
    connections: usize,
    uid: Option<u32>,
    gid: Option<u32>,
) -> Result<DataLocation, Box<dyn std::error::Error>> {
    if spec.starts_with("nfs://") {
        #[cfg(feature = "nfs")]
        {
            return parse_nfs_location(spec, connections, uid, gid);
        }
        #[cfg(not(feature = "nfs"))]
        {
            let _ = (connections, uid, gid);
            return Err("NFS support not compiled in. Rebuild with --features nfs".into());
        }
    }
    if spec.starts_with("smb://") || spec.starts_with(r"smb:\\") {
        #[cfg(feature = "smb")]
        {
            return Ok(DataLocation::smb(bifrost::smb::SmbLocation::from_url(
                spec,
            )?));
        }
        #[cfg(not(feature = "smb"))]
        {
            let _ = (connections, uid, gid);
            return Err("SMB support not compiled in. Rebuild with --features smb".into());
        }
    }
    let _ = (connections, uid, gid);
    Ok(DataLocation::local(PathBuf::from(spec)))
}

fn print_summary(stats: &bifrost::frame::TransferStats, elapsed: Duration) {
    let elapsed_secs = elapsed.as_secs_f64().max(0.001);
    let file_rate = stats.files_transferred as f64 / elapsed_secs;
    let byte_rate = stats.bytes_transferred as f64 / elapsed_secs;
    println!(
        "Backup complete: {} files ({:.2} MiB), {} dirs, {} failed files, {} failed dirs, elapsed {}, {:.2} files/s, {}/s",
        stats.files_transferred,
        stats.bytes_transferred as f64 / (1024.0 * 1024.0),
        stats.dirs_created,
        stats.files_failed,
        stats.dirs_failed,
        format_elapsed(elapsed),
        file_rate,
        format_bytes(byte_rate),
    );
}

fn format_elapsed(elapsed: Duration) -> String {
    let secs = elapsed.as_secs();
    let millis = elapsed.subsec_millis();
    if secs >= 60 {
        format!("{}m {}.{:03}s", secs / 60, secs % 60, millis)
    } else {
        format!("{}.{:03}s", secs, millis)
    }
}

fn format_bytes(bytes: f64) -> String {
    const UNITS: [&str; 5] = ["B", "KiB", "MiB", "GiB", "TiB"];
    let mut value = bytes;
    let mut unit = 0;
    while value >= 1024.0 && unit < UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    format!("{value:.2} {}", UNITS[unit])
}
